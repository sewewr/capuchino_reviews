"""
Проверка: узнаются ли филиалы по адресам в том виде, в каком их пишут площадки.
Сверяем по адресу из справочника, а не по номеру записи в базе:
номера зависят от порядка заливки и ничего не говорят о правильности.

    DATABASE_URL=postgresql://... python check_match.py
"""
import os
import storage

# (площадка, адрес как в письме, ожидаемое начало адреса в справочнике или None)
PROBES = [
    ("yandex", "Волгоград, Рабоче-Крестьянская улица, 9Б", "Рабоче-Крестьянская ул., 9Б"),
    ("yandex", "Волгоград, переулок Ногина, 48", "пер. Ногина, 48"),
    ("yandex", "Волгоград, Краснознаменская улица, 9", "Краснознаменская ул., 9"),
    ("yandex", "Волгоград, улица Рокоссовского, 54", "ул. Рокоссовского, 54"),
    ("yandex", "Волгоград, проспект имени В. И. Ленина, 54Б", "просп. имени В.И. Ленина, 54Б"),
    ("yandex", "Волгоград, проспект Ленина, 54Б", "просп. имени В.И. Ленина, 54Б"),
    ("yandex", "Волгоград, бульвар 30-летия Победы, 21", "бул. 30-летия Победы, 21"),
    ("yandex", "Волгоград, улица Николая Отрады, 26", "ул. Николая Отрады, 26"),
    ("yandex", "Волгоград, проспект Маршала Жукова, 117", "просп. Маршала Жукова, 117"),
    ("yandex", "Волгоград, улица Генерала Штеменко, 5", "ул. Генерала Штеменко, 5"),
    ("yandex", "Волгоград, Университетский проспект, 107", "Университетский просп., 107"),
    # 2ГИС пишет тип улицы после названия — формат из реального письма
    ("2gis", "Волгоград, 30-летия Победы бульвар, 21", "бул. 30-летия Победы, 21"),
    ("2gis", "Волгоград, Рокоссовского улица, 54", "ул. Рокоссовского, 54"),
    ("2gis", "Волгоград, Ленина проспект, 54Б", "просп. имени В.И. Ленина, 54Б"),
    ("2gis", "Волгоград, Университетский проспект, 107", "Университетский просп., 107"),
    # заведомо чужие — не должны совпасть
    ("yandex", "Волгоград, улица Рокоссовского, 62", None),
    ("yandex", "Волгоград, улица Мира, 1", None),
    ("2gis", "Волгоград, Мира улица, 1", None),
]

conn = storage.connect(os.environ["DATABASE_URL"])
ok = bad = 0
for source, address, expected in PROBES:
    found = storage.find_branch(conn, source, address)
    got = found.address if found else None
    good = (got is None and expected is None) or (
        got is not None and expected is not None and got.startswith(expected)
    )
    ok, bad = (ok + 1, bad) if good else (ok, bad + 1)
    print(f"  {'✓' if good else '✗'} [{source:<6}] {address:<44} -> {got or 'не найден'}")
print(f"\n  совпало {ok}, ошибок {bad}")
conn.close()
