"""Проверка: узнаются ли филиалы по адресам в том виде, в каком их пишет Яндекс."""
import os, storage

# Слева — как адрес может прийти в письме (формат Яндекса: город первым,
# тип улицы после названия). Справа — какой филиал ожидаем.
PROBES = [
    ("Волгоград, Рабоче-Крестьянская улица, 9Б", 8),
    ("Волгоград, переулок Ногина, 48", 1),
    ("Волгоград, Краснознаменская улица, 9", 2),
    ("Волгоград, улица Рокоссовского, 54", 3),
    ("Волгоград, проспект имени В. И. Ленина, 54Б", 4),
    ("Волгоград, проспект Ленина, 54Б", 4),
    ("Волгоград, бульвар 30-летия Победы, 21", 5),
    ("Волгоград, улица Николая Отрады, 26", 6),
    ("Волгоград, проспект Маршала Жукова, 117", 7),
    ("Волгоград, улица Генерала Штеменко, 5", 9),
    ("Волгоград, Университетский проспект, 107", 10),
    ("Волгоград, улица Рокоссовского, 62", None),   # чужой дом — не должен совпасть
    ("Волгоград, улица Мира, 1", None),             # чужая улица
]

conn = storage.connect(os.environ["DATABASE_URL"])
ok = bad = 0
for address, expected in PROBES:
    found = storage.find_branch(conn, "yandex", address)
    got = found.id if found else None
    good = got == expected
    ok, bad = (ok + 1, bad) if good else (ok, bad + 1)
    mark = "✓" if good else "✗"
    print(f"  {mark} {address:<46} -> {got}  (ждали {expected})")
print(f"\n  совпало {ok}, ошибок {bad}")
conn.close()
