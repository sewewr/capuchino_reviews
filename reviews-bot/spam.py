"""
Распознавание рекламы под видом отзыва.

На площадках встречаются «отзывы» вида «Помогаем бизнесу усиливать репутацию
в Яндекс и 2ГИС. 2ГИС — 50 отзывов: 3 700 ₽…». Звёзды они ставят, но
отвечать на них не нужно, и в статистику они не должны попадать.

Правило осторожное: одного-двух признаков мало (гость может написать «торт
за 1500 ₽, нашла вас в 2ГИС»). Рекламой считаем, только если есть продающая
формулировка («усилим репутацию», «накрутка», «50 отзывов — 3 700 ₽») и ещё
два признака (цена, площадки, контакты, «пишите») — или две продающие сразу.
Что правило пропустит, сотрудник помечает кнопкой «🚫 Реклама».
"""

from __future__ import annotations

import re

# Признаки, без которых рекламой не считаем
_SELLING = [
    ("продающая формулировка", re.compile(
        r"(?:усил|управлен|улучш|повыш|защит)\w* репутаци|репутаци\w* (?:бизнес|компани)|"
        r"накрут|продвижени|продвинем|раскрут|помогаем бизнес|поможем бизнес|"
        r"для вашего бизнеса|для бизнеса|под ключ|увелич\w* (?:рейтинг|продаж|поток)|"
        r"подн\w* рейтинг|вывед\w* в топ|в топ[- ]?\d|удал\w* негатив|"
        r"оптимизаци\w* карточ|seo\b|сео\b|smm\b", re.I)),
    ("отзывы как товар", re.compile(
        r"\d+\s*(?:шт\.?\s*)?отзыв\w*\W{0,5}(?:за|от|по)?\s*\d[\d\s]*(?:₽|р\b|руб)|"
        r"отзыв\w*\s*(?:от|по|за)\s*\d+\s*(?:₽|р\b|руб)|"
        r"отзыв\w*.{0,40}?(?:₽|руб\w*)\.?\s*(?:за|/)\s*(?:штуку|шт\b)|"
        r"(?:₽|руб\w*)\.?\s*(?:за|/)\s*(?:1 )?отзыв|"
        r"(?:купить|закаж\w*|продаж\w*|продаём|продаем)\s+отзыв", re.I)),
]

# Дополнительные признаки
_EXTRA = [
    ("цена", re.compile(r"\d[\d\s]*(?:₽|руб\b|руб\.|рублей|р\.(?:\s|$))", re.I)),
    ("площадки", re.compile(r"яндекс|2\s?гис|авито|google|гугл|zoon|отзовик", re.I)),
    ("контакт", re.compile(
        r"t\.me/|wa\.me/|(?<![\w.])@[a-z0-9_]{4,}|whats\s?app|ватсап|вотсап|телеграм|"
        r"telegram|\+7[\s(-]*\d{3}|(?<!\d)8[\s(-]*9\d{2}[\s)-]*\d{3}|https?://|www\.", re.I)),
    ("предложение", re.compile(
        r"пишите|обращайтесь|звоните|скидк|акци[яи]|прайс|тариф|пакет\w*|недорого|дёшево|дешево|"
        r"бесплатн\w* (?:консультац|аудит)", re.I)),
]


def detect(text: str | None) -> tuple[bool, list[str]]:
    """(реклама ли, какие признаки нашлись)."""
    t = " ".join((text or "").split())
    if not t:
        return False, []

    selling = [name for name, rx in _SELLING if rx.search(t)]
    extra = [name for name, rx in _EXTRA if rx.search(t)]
    found = selling + extra
    # Продающая формулировка плюс два признака — или две продающие сразу.
    return (len(selling) >= 2 or (len(selling) == 1 and len(extra) >= 2)), found


def is_spam(text: str | None) -> bool:
    return detect(text)[0]
